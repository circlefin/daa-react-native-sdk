/**
 * Whether a value uses the hyphenated UUID form accepted by DAA path
 * parameters. UUIDs are strings at the TypeScript boundary, so this is the
 * runtime guard before one becomes part of a request path.
 */
export function isUuid(value: string): boolean {
  return /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(value)
}

/** Whether a value is an RFC 4122 UUID v4, including a valid variant nibble. */
export function isUuidV4(value: string): boolean {
  return /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(value)
}
